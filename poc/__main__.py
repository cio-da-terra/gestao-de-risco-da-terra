"""Run the proof of concept and write poc/results/.

    .venv/bin/python -m poc.fetch                 # once, to fill the database
    .venv/bin/python -m poc [--municipio Jaguaré] [--cost 20000]
"""

from __future__ import annotations

import argparse
import warnings
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from . import breakeven, config, data  # noqa: E402
from . import price_model as pm  # noqa: E402
from . import yield_model as ym  # noqa: E402

OUT = Path(__file__).resolve().parent / "results"
INK, MUTED, BAND, ACCENT, ALERT = "#1C2420", "#6B746F", "#CFE3D7", "#1F5C45", "#B4541A"


def _style(ax, title):
    ax.set_title(title, loc="left", fontsize=11, color=INK)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.tick_params(colors=MUTED, labelsize=9)
    ax.grid(axis="y", color="#E6E3DA", linewidth=0.8)
    ax.set_axisbelow(True)


def plot_yield(res, code, name, model, path):
    d = res[(res.model == model) & (res.code == code) & (res.year >= ym.REPORT_START)]
    fig, ax = plt.subplots(figsize=(8, 3.6))
    ax.fill_between(d.year, d.lo_aci, d.hi_aci, color=BAND, label="80% interval (ACI)")
    ax.plot(d.year, d.pred, color=ACCENT, lw=2, label=f"Forecast ({model})")
    ax.plot(d.year, d.y, "o", color=INK, ms=5, label="Actual (PAM)")
    miss = d[~d.cov_aci]
    ax.plot(miss.year, miss.y, "o", mfc="none", mec=ALERT, ms=11, mew=1.5, label="Outside interval")
    ax.set_ylabel("sacas/ha", color=MUTED, fontsize=9)
    _style(ax, f"Conilon yield, {name}: forecast in Feb vs harvest")
    ax.legend(frameon=False, fontsize=8, loc="upper left")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_price(res, model, path):
    d = res[(res.model == model) & (res.origin >= pm.REPORT_START)].sort_values("target_date")
    fig, ax = plt.subplots(figsize=(8, 3.6))
    ax.fill_between(d.target_date, d.lo_aci, d.hi_aci, color=BAND, label="80% interval (ACI)")
    ax.plot(d.target_date, d.p_pred, color=ACCENT, lw=1.5, label=f"Forecast 6 months ahead ({model})")
    ax.plot(d.target_date, d.p_actual, color=INK, lw=1.2, label="Actual")
    ax.set_ylabel("R$/saca", color=MUTED, fontsize=9)
    _style(ax, "Robusta price in BRL (Pink Sheet × PTAX)")
    ax.legend(frameon=False, fontsize=8, loc="upper left")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_breakeven(be, name, path):
    fig, ax = plt.subplots(figsize=(8, 3.4))
    ax.bar(be.year, be.p_loss * 100, color=ACCENT, width=0.6, label="P(revenue < cost), price open")
    ax.plot(be.year, be.p_loss_price_locked * 100, "_", color=INK, ms=14, mew=2,
            label="Same, price locked in Feb")
    loss = be[be.actual_loss]
    ax.plot(loss.year, [102] * len(loss), "v", color=ALERT, ms=8, label="Actual loss year")
    ax.set_ylim(0, 108)
    ax.set_ylabel("%", color=MUTED, fontsize=9)
    _style(ax, f"Chance of not covering costs, {name} (illustrative cost)")
    ax.legend(frameon=False, fontsize=8, loc="upper right")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser(prog="python -m poc")
    ap.add_argument("--municipio", default="Jaguaré")
    ap.add_argument("--cost", type=float, default=20000.0,
                    help="ILLUSTRATIVE cost per hectare in 2025 R$ (deflated by IPCA)")
    args = ap.parse_args()
    warnings.filterwarnings("ignore")
    OUT.mkdir(exist_ok=True)

    con = data.connect()
    muns = data.municipios(con)
    code = int(muns.loc[muns.name == args.municipio, "code"].iloc[0])

    # Yield
    feats = ym.build_features(data.yields(con, muns), data.weather(con, muns), data.oni(con))
    ypreds, coefs = ym.backtest(feats)
    yres = ym.add_intervals(ypreds)
    ysum = ym.summarise(yres)
    ybest = ysum["MAE (sc/ha)"].idxmin()

    # Price
    pfeat = pm.build(data.price_brl_saca(con), data.oni(con))
    pres = pm.add_intervals(pm.backtest(pfeat))
    psum = pm.summarise(pres)
    pbest = psum["MAE (R$/saca)"].idxmin()

    # Break-even
    ipca = data._series(con, "bcb:ipca_mensal").set_index("ref_date")["value"].sort_index()
    be = breakeven.run(yres, pres, ipca, code, args.cost, ybest, pbest)
    be = be[be.year >= ym.REPORT_START].reset_index(drop=True)

    plot_yield(yres, code, args.municipio, ybest, OUT / "yield_backtest.png")
    plot_price(pres, pbest, OUT / "price_backtest.png")
    plot_breakeven(be, args.municipio, OUT / "breakeven.png")

    yres.to_csv(OUT / "yield_predictions.csv", index=False)
    pres.to_csv(OUT / "price_predictions.csv", index=False)
    be.to_csv(OUT / "breakeven.csv", index=False)

    with open(OUT / "summary.md", "w") as f:
        f.write(f"# PoC results\n\nGenerated by `python -m poc`. Municipality for the "
                f"break-even demo: {args.municipio}; illustrative cost R$ {args.cost:,.0f}/ha "
                f"(2025 reais).\n\n")
        f.write(f"## Yield (18 municipalities, forecast years {ym.REPORT_START}–{feats.year.max()})\n\n")
        f.write(ysum.to_markdown() + "\n\n")
        f.write("Ridge coefficients (standardised, last fit):\n\n")
        f.write(coefs.rename(index=ym.FEATURE_LABELS).round(3).to_frame("coef").to_markdown() + "\n\n")
        f.write(f"## Price (origins from {pm.REPORT_START[:7]}, 6 months ahead)\n\n")
        f.write(psum.to_markdown() + "\n\n")
        f.write(f"## Break-even ({ybest} yield × {pbest} price)\n\n")
        cols = ["year", "cost_ha", "yield_p50", "breakeven_price", "price_feb", "p_loss",
                "p_loss_price_locked", "actual_yield", "actual_price", "actual_loss"]
        f.write(be[cols].round(2).to_markdown(index=False) + "\n")
    print((OUT / "summary.md").read_text())


if __name__ == "__main__":
    main()
