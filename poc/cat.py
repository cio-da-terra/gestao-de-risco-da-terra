"""Run CAT-lite inside the PoC backtest and compare it with our models.

    .venv/bin/python -m poc.cat      # ~3 min on CPU; writes poc/results/cat.md

Same data, same rolling origin (train on years <= Y-2), same online
conformal + ACI intervals as the other yield models, so the comparison is
like for like.
"""

from __future__ import annotations

import warnings

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from . import cat_model as cm  # noqa: E402
from . import data  # noqa: E402
from . import yield_model as ym  # noqa: E402
from .__main__ import ACCENT, BAND, INK, MUTED, OUT, _style  # noqa: E402

MONTH_LABELS = ["Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec", "Jan", "Feb"]


def factory():
    models = ym.make_models()
    models.pop("mlp")
    models["cat"] = cm.CATRegressor()
    return models


def per_year_mae(res):
    r = res[res.year >= ym.REPORT_START]
    return r.assign(ae=(r.pred - r.y).abs()).pivot_table(index="year", columns="model", values="ae")


def plot_attention(prior, learned, pooled, path):
    x = np.arange(12)
    fig, ax = plt.subplots(figsize=(8, 3.4))
    ax.bar(x, pooled * 100, color=BAND, width=0.7, label="Attention used on 2025 forecasts")
    ax.plot(x, prior / prior.sum() * 100, color=INK, ls="--", lw=1.2, label="Phenology prior (initial)")
    ax.plot(x, learned * 100, color=ACCENT, lw=2, marker="o", ms=4, label="Learned phenology mask")
    for a, b, name in ((0, 3, "branch growth"), (4, 7, "flowering"), (8, 11, "grain filling")):
        ax.annotate(name, ((a + b) / 2, 0.5), ha="center", fontsize=8, color=MUTED)
    ax.set_xticks(x, MONTH_LABELS)
    ax.set_ylabel("% of attention", color=MUTED, fontsize=9)
    _style(ax, "CAT-lite: which months the model attends to (Mar Y-1 → Feb Y)")
    ax.legend(frameon=False, fontsize=8, loc="upper left")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def main():
    warnings.filterwarnings("ignore")
    con = data.connect()
    muns = data.municipios(con)
    wx = data.weather(con, muns)
    feats = ym.build_features(data.yields(con, muns), wx, data.oni(con), data.lspa_vintages(con))
    feats = cm.add_monthly_sequences(feats, wx)

    last = {}

    def keep_last(name, model, Y, test):
        if name == "cat":
            last["model"], last["Y"] = model, Y

    preds, _ = ym.backtest(feats, factory=factory, on_fit=keep_last)
    res = ym.add_intervals(preds)
    summary = ym.summarise(res)
    yearly = per_year_mae(res).round(1)

    m = last["model"]
    learned = m.learned_phenology()
    pooled = m.pool_weights_.mean(0)
    plot_attention(cm.PHENO_PRIOR, learned, pooled, OUT / "cat_attention.png")
    stage = pd.DataFrame({"stage": cm.STAGES, "prior": cm.PHENO_PRIOR / cm.PHENO_PRIOR.sum(),
                          "learned": learned, "used": pooled}).groupby("stage", sort=False).sum()

    n_params = sum(p.numel() for p in m.models[0].parameters())
    with open(OUT / "cat.md", "w") as f:
        f.write("# CAT-lite vs PoC models\n\nGenerated by `python -m poc.cat`. Same rolling "
                f"backtest and conformal/ACI intervals as the PoC; forecast years "
                f"{ym.REPORT_START}–{feats.year.max()}. CAT-lite: {n_params:,} parameters per "
                f"network, {len(m.models)}-seed ensemble, ~{len(feats):,} rows in total.\n\n")
        f.write(summary.to_markdown() + "\n\n## Error by year (sacas/ha)\n\n")
        f.write(yearly.to_markdown() + "\n\n## Attention by crop stage (last fit)\n\n")
        f.write(stage.round(3).to_markdown() + "\n\n![Attention](cat_attention.png)\n")
    print((OUT / "cat.md").read_text())


if __name__ == "__main__":
    main()
